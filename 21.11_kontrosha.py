def isPrime(k):
    if k < 2:
        return False
    d = 2
    while d * d <= k:
        if k % d == 0:
            return False
        d += 1
    return True



def nextPrime(n):
    k = n + 1
    while not isPrime(k):
        k += 1
    return k

