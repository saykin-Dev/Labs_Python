def isInteger(stroka):
    stroka = stroka.strip()
    if stroka == "":
        return False
    if stroka[0] == '+' or stroka[0] == '-':
        stroka = stroka[1:]
    if stroka == "":
        return False
    for znak in stroka:
        if znak < '0' or '9' > znak:
            return False
    return True

